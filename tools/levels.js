// Usage: node tools/levels.js [--write]   (then node tools/gen_spec.js)
// FM Wavelet Synthesizer: matches the loudness of the factory presets (master volume per preset). --write stores the
// result in tools/spec.js (block between the LEVELS markers).
const R = require('path').join(__dirname, '..') + '/';
const fs = require('fs');
const S = require(R + 'web/js/spec.js'), C = require(R + 'web/js/core.js')(S);
const sr = 48000, P = C.P;
function loud(values, notes, win) {
  const eng = new C.Engine(sr); values.forEach((v, i) => eng.setParam(i, v));
  const n = Math.ceil(3 * sr / 128), L = new Float32Array(128), Rr = new Float32Array(128), pw = new Float32Array(n * 128);
  let pk = 0;
  for (let b = 0; b < n; b++) {
    if (b === 0) for (const k of notes) eng.noteOn(k, 0.85);
    if (b === Math.floor(2.5 * sr / 128)) eng.allNotesOff();
    eng.process(L, Rr, 128);
    for (let i = 0; i < 128; i++) { pk = Math.max(pk, Math.abs(L[i]), Math.abs(Rr[i])); pw[b * 128 + i] = 0.5 * (L[i] * L[i] + Rr[i] * Rr[i]); }
  }
  const W = Math.round(win * sr); let s = 0, best = 0;
  for (let i = 0; i < pw.length; i++) { s += pw[i]; if (i >= W) s -= pw[i - W]; if (i >= W - 1) best = Math.max(best, s / W); }
  return { db: 10 * Math.log10(best + 1e-20), pk };
}
const TARGET = -14, mp = S.PARAMS[P.master], out = {};
for (const pr of S.PRESETS) {
  const drums = pr.cat === 'Drums & Perc', mono = pr.values[P.v_voices] <= 1;
  const r = loud(pr.values, mono ? [60] : [60, 64, 67], drums ? 0.05 : 0.2);
  const t = TARGET - (drums ? 3 : 0) - (mono ? 4 : 0), cur = pr.values[P.master];
  let m = Math.max(mp.min, Math.min(mp.max, Math.round((cur + t - r.db) * 2) / 2));
  const pk = r.pk * Math.pow(10, (m - cur) / 20);
  if (pk > 0.98) m = Math.round((m - 20 * Math.log10(pk / 0.98) - 0.25) * 2) / 2;
  out[pr.name] = m;
  console.log(`${pr.name.padEnd(20)} ${r.db.toFixed(1).padStart(6)} dB peak ${r.pk.toFixed(2)}${mono ? ' (mono)' : ''}  master ${cur} -> ${m}`);
}
if (process.argv.includes('--write')) {
  const f = R + 'tools/spec.js';
  let s = fs.readFileSync(f, 'utf8');
  const block = '// LEVELS (generated by the loudness check: master volume per preset, so the presets sound equally loud)\n' +
    'const LEVELS = ' + JSON.stringify(out, null, 0).replace(/,"/g, ', "').replace(/":/g, '": ') + ';\n' +
    'for (const p of PRESET_LIST) if (LEVELS[p.name] !== undefined && p.v.master === undefined) p.v.master = LEVELS[p.name];\n// END LEVELS\n';
  const a = s.indexOf('// LEVELS ('), b = s.indexOf('// END LEVELS\n');
  if (a >= 0 && b > a) s = s.slice(0, a) + block + s.slice(b + '// END LEVELS\n'.length);
  else { const at = s.indexOf('const CATEGORIES = ['); s = s.slice(0, at) + block + '\n' + s.slice(at); }
  fs.writeFileSync(f, s); console.log('written');
}
