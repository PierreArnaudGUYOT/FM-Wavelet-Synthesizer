// Generates web/js/spec.js from tools/spec.js + tools/wavelets.json.
// Usage: node tools/gen_spec.js
'use strict';
const fs = require('fs');
const path = require('path');
const spec = require('./spec.js');
const wav = JSON.parse(fs.readFileSync(path.join(__dirname, 'wavelets.json'), 'utf8'));

const root = path.join(__dirname, '..');
const { DEVICE, APP, DEFAULT_PRESET, PARAMS, SECTIONS, PRESETS, FAVOURITES, CATEGORIES } = spec;
const presetValues = PRESETS.map(pr => ({
  name: pr.name,
  cat: pr.cat,
  values: PARAMS.map(p => (pr.v[p.key] !== undefined ? pr.v[p.key] : p.def)),
}));
const names = PARAMS.find(p => p.key === 'op1_wave').choices;
const wavelets = wav.order.map((n, i) => ({ id: n, name: names[i], h: wav.h[n] }));

const web = {
  DEVICE, APP, DEFAULT_PRESET: PRESETS.findIndex(p => p.name === DEFAULT_PRESET), FAVOURITES, CATEGORIES, PARAMS, SECTIONS,
  WAVELETS: wavelets, PRESETS: presetValues,
};
const out = '// Copyright (C) 2026 Pierre Arnaud GUYOT (OktoPierre)\n// SPDX-License-Identifier: GPL-3.0-or-later\n// GENERATED by tools/gen_spec.js — do not edit.\n' +
  'var WS_SPEC = ' + JSON.stringify(web, null, 1) + ';\n' +
  "if (typeof module !== 'undefined') module.exports = WS_SPEC;\n";
fs.writeFileSync(path.join(root, 'web', 'js', 'spec.js'), out);
const widgets = SECTIONS.reduce((n, s) => n + s.widgets.length, 0);
console.log(`generated: ${PARAMS.length} params, ${widgets} widgets, ${SECTIONS.length} sections, ${PRESETS.length} presets, ${wavelets.length} wavelets`);
